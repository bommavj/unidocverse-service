"""
coi_router.py
=============
Certificate of Insurance (COI) Automation API
"""
import logging, uuid
from datetime import date, timedelta
from typing import Optional, List
from fastapi import APIRouter, Depends, HTTPException
from pydantic import BaseModel
from sqlalchemy import text
from sqlalchemy.orm import Session
from app.core.database import get_db

logger = logging.getLogger(__name__)
router = APIRouter(prefix="/api/ams/coi", tags=["coi"])


class COIRequest(BaseModel):
    client_id: str
    holder_name: str
    holder_address: Optional[str] = None
    holder_email: Optional[str] = None
    purpose: Optional[str] = None
    policy_ids: Optional[List[str]] = None
    additional_insured: Optional[str] = None
    requested_by: Optional[str] = None


@router.post("/request")
def create_coi_request(req: COIRequest, db: Session = Depends(get_db)):
    """Create a COI request and auto-generate the certificate."""
    # Get client
    client = db.execute(text("SELECT * FROM clients WHERE id = :id"),
                        {"id": req.client_id}).fetchone()
    if not client:
        raise HTTPException(status_code=404, detail="Client not found")

    # Get policies to include
    if req.policy_ids:
        policies = db.execute(text("""
            SELECT * FROM policies WHERE id = ANY(:ids) AND client_id = :client_id
        """), {"ids": req.policy_ids, "client_id": req.client_id}).fetchall()
    else:
        policies = db.execute(text("""
            SELECT * FROM policies
            WHERE client_id = :id AND status = 'active'
            ORDER BY line_of_business
        """), {"id": req.client_id}).fetchall()

    if not policies:
        raise HTTPException(status_code=400, detail="No active policies found for client")

    # Create request record
    req_id = str(uuid.uuid4())
    db.execute(text("""
        INSERT INTO coi_requests
            (id, client_id, requested_by, holder_name, holder_address,
             holder_email, purpose, policy_ids, additional_insured, status)
        VALUES
            (:id, :client_id, :req_by, :holder, :address,
             :email, :purpose, :pol_ids, :additional, 'generating')
    """), {
        "id": req_id, "client_id": req.client_id,
        "req_by": req.requested_by, "holder": req.holder_name,
        "address": req.holder_address, "email": req.holder_email,
        "purpose": req.purpose,
        "pol_ids": [str(p.id) for p in policies],
        "additional": req.additional_insured,
    })

    # Build ACORD 25 certificate data
    client_name = (
        client.business_name if client.client_type == "commercial"
        else f"{client.first_name} {client.last_name}"
    ).strip()

    coverages = []
    for policy in policies:
        coverage_data = policy.coverage_summary or {}
        coverages.append({
            "type": _lob_to_acord(policy.line_of_business),
            "carrier": policy.carrier_name,
            "policy_number": policy.policy_number,
            "effective": str(policy.effective_date) if policy.effective_date else "",
            "expiry": str(policy.expiry_date) if policy.expiry_date else "",
            "premium": float(policy.premium_amount or 0),
            "limits": _build_limits(policy.line_of_business, coverage_data),
        })

    certificate_data = {
        "certificate_number": "",  # Auto-generated by trigger
        "issue_date": str(date.today()),
        "producer": {
            "name": "UniDocVerse Insurance Agency",
            "address": "",
            "phone": "",
        },
        "insured": {
            "name": client_name,
            "address": f"{client.address_line1 or ''} {client.city or ''} {client.state or ''} {client.zip or ''}".strip(),
            "client_number": client.client_number,
        },
        "coverages": coverages,
        "certificate_holder": {
            "name": req.holder_name,
            "address": req.holder_address or "",
            "email": req.holder_email or "",
        },
        "additional_insured": bool(req.additional_insured),
        "additional_insured_name": req.additional_insured or "",
        "description_of_operations": req.purpose or "",
        "special_conditions": "",
    }

    # Save certificate
    cert_id = str(uuid.uuid4())
    valid_until = date.today() + timedelta(days=365)

    db.execute(text("""
        INSERT INTO coi_certificates
            (id, request_id, client_id, certificate_data, valid_until, issued_by)
        VALUES
            (:id, :req_id, :client_id, :data::jsonb, :valid_until, :issued_by)
    """), {
        "id": cert_id, "req_id": req_id, "client_id": req.client_id,
        "data": __import__('json').dumps(certificate_data),
        "valid_until": valid_until,
        "issued_by": req.requested_by or "system",
    })

    # Update request status
    db.execute(text("""
        UPDATE coi_requests SET status = 'completed', completed_at = NOW() WHERE id = :id
    """), {"id": req_id})
    db.commit()

    # Fetch certificate number (generated by trigger)
    cert = db.execute(text(
        "SELECT certificate_number FROM coi_certificates WHERE id = :id"
    ), {"id": cert_id}).fetchone()

    certificate_data["certificate_number"] = cert.certificate_number if cert else ""

    return {
        "request_id": req_id,
        "certificate_id": cert_id,
        "certificate_number": certificate_data["certificate_number"],
        "client_name": client_name,
        "holder_name": req.holder_name,
        "policies_included": len(policies),
        "valid_until": str(valid_until),
        "certificate_data": certificate_data,
        "message": "Certificate of Insurance generated successfully"
    }


@router.get("/client/{client_id}")
def get_client_cois(client_id: str, db: Session = Depends(get_db)):
    certs = db.execute(text("""
        SELECT c.*, r.holder_name, r.holder_email, r.purpose
        FROM coi_certificates c
        JOIN coi_requests r ON r.id = c.request_id
        WHERE c.client_id = :id
        ORDER BY c.issued_at DESC
    """), {"id": client_id}).fetchall()
    return {"certificates": [dict(r._mapping) for r in certs]}


@router.get("/{cert_id}")
def get_certificate(cert_id: str, db: Session = Depends(get_db)):
    cert = db.execute(text("""
        SELECT c.*, r.holder_name, r.holder_email, r.purpose, r.additional_insured
        FROM coi_certificates c
        JOIN coi_requests r ON r.id = c.request_id
        WHERE c.id = :id
    """), {"id": cert_id}).fetchone()
    if not cert:
        raise HTTPException(status_code=404, detail="Certificate not found")
    return dict(cert._mapping)


@router.get("/expiring/soon")
def get_expiring_cois(days: int = 30, db: Session = Depends(get_db)):
    rows = db.execute(text("""
        SELECT c.*, r.holder_name, r.holder_email,
               cl.first_name, cl.last_name, cl.business_name
        FROM coi_certificates c
        JOIN coi_requests r ON r.id = c.request_id
        JOIN clients cl ON cl.id = c.client_id
        WHERE c.valid_until BETWEEN CURRENT_DATE AND CURRENT_DATE + :days
          AND c.is_expired = FALSE
        ORDER BY c.valid_until ASC
    """), {"days": days}).fetchall()
    return {"expiring_certificates": [dict(r._mapping) for r in rows]}


def _lob_to_acord(lob: str) -> str:
    mapping = {
        "general_liability": "Commercial General Liability",
        "commercial_property": "Commercial Property",
        "auto": "Automobile Liability",
        "workers_comp": "Workers Compensation",
        "umbrella": "Umbrella/Excess Liability",
        "homeowners": "Homeowners",
        "bop": "Business Owners Policy",
    }
    return mapping.get(lob, lob.replace("_", " ").title())

def _build_limits(lob: str, coverage: dict) -> dict:
    if lob == "general_liability":
        return {
            "each_occurrence": coverage.get("each_occurrence", 1000000),
            "general_aggregate": coverage.get("aggregate", 2000000),
            "products_aggregate": coverage.get("products_aggregate", 2000000),
            "personal_injury": coverage.get("personal_injury", 1000000),
        }
    elif lob == "auto":
        return {"combined_single_limit": coverage.get("liability", 1000000)}
    elif lob == "workers_comp":
        return {"el_each_accident": coverage.get("el_each_accident", 500000)}
    return {"limit": coverage.get("limit", coverage.get("dwelling", 0))}